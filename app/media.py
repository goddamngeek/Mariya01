"""Что бот знает про фильмы и сериалы.

Кино устроено НЕ так, как книги, и копировать книжную модель было бы
ошибкой. Книгу читают неделями, поэтому «сейчас читаю» у неё осмысленно.
Фильм смотрят за вечер — «сейчас смотрю» у фильмов было бы всегда пустым.
Долгое состояние есть только у сериалов, потому и разделены эти два вида.

Зато у кино есть то, чего нет у книг: список «хочу посмотреть». Он тут
главный — ради него всё и заводится.

КОЛЛЕКЦИЯ ОБЩАЯ, СОСТОЯНИЕ ЛИЧНОЕ. Одна заметка на фильм, завести может
любой из двоих: смотрят вместе, и списка «моё кино» с «её кино» быть не
должно. А вот посмотрел ли ты его — личное, и живёт лейблом с именем
человека на той же заметке:

    ни одного личного лейбла   — хочу посмотреть
    watchingОСТАП              — смотрю (только сериалы)
    watchedОСТАП = дата        — посмотрел
    droppedОСТАП               — не буду смотреть / бросил

Отсюда бесплатно получается то, чего не дала бы ни чисто общая схема, ни
чисто личная: Маша добавила фильм — он появился у тебя в «хочу
посмотреть»; она посмотрела, ты нет — у неё он в «посмотрел», у тебя
по-прежнему в «хочу».

Лейбла `owner`, как у книг, здесь намеренно нет: он делил бы то, что делить
не нужно.
"""

from dataclasses import dataclass


# Лейблы кириллицей в значении, но латиницей в имени: имя атрибута в Trilium
# участвует в поиске и в промоушене, и смешивать там алфавиты — напрашиваться
# на невоспроизводимую опечатку. Имя человека приклеивается как есть
# («watchedОСТАП»), потому что оно и так уже кириллическое во всём проекте
# (см. app/people.py).
WATCHED = "watched"
WATCHING = "watching"
DROPPED = "dropped"

# Состояния списков. Строками, а не Enum: они ездят внутри callback_data
# кнопок, где всё равно станут строкой.
#
# DROPPED — и состояние, и префикс лейбла выше: это одна и та же строка
# намеренно, потому что «бросил» — единственное состояние, у которого нет
# отдельного имени. У остальных они разные (DONE хранится как watched…),
# и путать их не стоит.
WANT = "want"
IN_PROGRESS = "in_progress"
DONE = "done"


@dataclass(frozen=True)
class MediaKind:
    """Чем фильмы отличаются от сериалов — и это весь список отличий.

    Их так мало, что заводить два набора кода незачем: один вид передаётся
    параметром, и списки, карточки, кнопки и диалог оценки остаются общими.
    """

    slug: str              # film / series — едет в callback_data кнопок
    parent_note: str       # заголовок родительской заметки в Trilium
    tmdb_path: str         # movie / tv — кусок пути в эндпоинтах TMDb
    has_in_progress: bool  # у фильмов False: «смотрю» им не показываем

    # Тексты, зависящие от рода слова. Без них пришлось бы писать
    # «Какой фильм/сериал показать?» — а это читается как черновик.
    one: str               # «фильм» / «сериал»
    accusative: str        # «Какой ФИЛЬМ показать?»
    want_empty: str        # что сказать, когда список пуст
    done_empty: str
    progress_empty: str


FILM = MediaKind(
    slug="film",
    parent_note="ФИЛЬМЫ",
    tmdb_path="movie",
    has_in_progress=False,
    one="фильм",
    accusative="Какой фильм показать?",
    want_empty="Список пуст. Напиши «хочу посмотреть …» — добавлю.",
    done_empty="Пока нет просмотренных фильмов.",
    progress_empty="",  # у фильмов этого состояния нет
)

SERIES = MediaKind(
    slug="series",
    parent_note="СЕРИАЛЫ",
    tmdb_path="tv",
    has_in_progress=True,
    one="сериал",
    accusative="Какой сериал показать?",
    want_empty="Список пуст. Напиши «хочу посмотреть …» — добавлю.",
    done_empty="Пока нет просмотренных сериалов.",
    progress_empty="Сейчас ничего не смотришь.",
)

KINDS = {FILM.slug: FILM, SERIES.slug: SERIES}


def by_slug(slug: str) -> MediaKind | None:
    return KINDS.get(slug)


def label_for(prefix: str, person_name: str) -> str:
    """«watched» + «ОСТАП» -> «watchedОСТАП».

    Имя человека приходит из app/people.py в верхнем регистре, и здесь оно
    не нормализуется намеренно: лейбл должен совпадать побайтово с тем, что
    уже записано в заметке, иначе состояние потеряется и фильм молча
    вернётся в «хочу посмотреть»."""
    return f"{prefix}{person_name}"
