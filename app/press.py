"""Нажатие кнопки, очищенное от формы конкретного транспорта.

Телеграм приносит его вложенным словарём callback_query, другой транспорт
принесёт иначе. Обработчикам в service.py нужны ровно эти четыре поля, а
раньше каждый выковыривал их из словаря сам — полсотни мест, знающих
устройство телеграмного апдейта.

Отдельным модулем, а не внутри channel.py: тот про то, куда бот отвечает, а
это про то, что боту пришло. К тому же channel.py импортирует транспорт, а
транспорт импортирует Press — сложи их вместе, и получится кольцо.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class Press:
    """id — чем ответить, чтобы у человека погас кружок ожидания на кнопке.
    message_id может отсутствовать: сообщение старше 48 часов телеграм в
    апдейте не приносит."""

    id: str
    data: str
    chat_id: int | None
    message_id: int | None
